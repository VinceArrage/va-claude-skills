#!/usr/bin/env python3
"""Per-task token/time metrics, INDEX regeneration, and session stamps for
dev-loop task ledgers.

Reads Tasks/<KEY>/ledger.md, finds the Claude Code session transcripts it
names (parent sessions and the agents they dispatched), sums token usage,
computes the wall-clock span, and (with --write) fills the ledger's metrics
block.

Usage:
  python task_metrics.py <task-dir> [--write] [--projects-root PATH]
  python task_metrics.py --all <tasks-dir> [--projects-root PATH]
  python task_metrics.py index <tasks-dir> [--write]
  python task_metrics.py stamp <task-dir> --session <uuid> --stage <Stage>
"""
import argparse
import json
import re
import sys
from datetime import datetime
from pathlib import Path

TS_FMT = "%Y-%m-%d %H:%M"
BEGIN, END = "<!-- metrics:begin -->", "<!-- metrics:end -->"
SESSION_RE = re.compile(r"^\s*-\s*session:\s*([0-9a-fA-F-]{8,})\b", re.M)
DEFAULT_PROJECTS_ROOT = Path.home() / ".claude" / "projects"
METRICS_HEADING_RE = re.compile(r"^##[ \t]+Metrics[ \t]*$", re.M)
NEXT_HEADING_RE = re.compile(r"^##[ \t]+\S", re.M)
HEADING_RE = re.compile(r"^##\s+(.+?)\s*$")
# Row parsing is section-scoped: only rows under `## Delegation log` are
# read, and only when that table's header actually has a Model column.
# Rows shaped like data rows in any other section are ignored.
DELEGATION_SECTION = "Delegation log"
# Optional annotation on a "- session:" line, e.g.
#   - session: <id> · stage: Execution
# Older ledgers have no annotation; those sessions roll up as "unannotated".
STAGE_RE = re.compile(r"stage:\s*([A-Za-z][A-Za-z -]*)")
STAGE_ORDER = ["Intake", "Planning", "Execution", "Verification",
               "Delivery", "Closeout"]
SESSIONS_HEADER = "Sessions (record at every wake-up):"
INDEX_BANNER = ("<!-- generated by task_metrics.py index — do not hand-edit. "
                "Change the ledger's Stage and Now/Next lines, then regenerate. -->")
KEYS = ("input", "output", "cache_read", "cache_create")


def parse_ledger(text):
    """Session ids from '- session:' lines (trailing annotations tolerated);
    Delegation log rows counted by their Model column into `dispatch_models`
    — only when that table's header actually has a Model column, so
    pre-0.3.0 ledgers (Date|To|What|Outcome) contribute nothing rather than
    misreading prose as a model name. Section scoping (the `## ` heading a
    row lives under) keeps similarly-shaped rows in other tables from being
    counted.

    Session lines may carry a `stage:` annotation (see STAGE_RE); the first
    annotation per session id wins, returned in `session_stages`.
    """
    sessions = []
    session_stages = {}
    dispatch_models = {}
    section = None
    delegation_model_idx = None
    for line in text.splitlines():
        line = line.strip()
        heading = HEADING_RE.match(line)
        if heading:
            section = heading.group(1).strip()
            delegation_model_idx = None
            continue
        sm = SESSION_RE.match(line)
        if sm:
            sid = sm.group(1)
            sessions.append(sid)
            stage = STAGE_RE.search(line[sm.end():])
            if stage and sid not in session_stages:
                session_stages[sid] = stage.group(1).strip(" -")
            continue
        if section != DELEGATION_SECTION or not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) < 3:
            continue
        if all(set(c) <= set("-: ") for c in cells):
            continue  # separator row
        if cells[0] == "Date":  # header row — locate the Model column
            delegation_model_idx = (cells.index("Model")
                                    if "Model" in cells else None)
            continue
        if delegation_model_idx is not None and len(cells) > delegation_model_idx:
            model = cells[delegation_model_idx] or "—"
            dispatch_models[model] = dispatch_models.get(model, 0) + 1

    return {"sessions": sessions, "session_stages": session_stages,
            "dispatch_models": dispatch_models}


def sum_usage(jsonl_path):
    tot = {"input": 0, "output": 0, "cache_read": 0, "cache_create": 0,
           "first": None, "last": None}
    with open(jsonl_path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                continue
            ts = rec.get("timestamp")
            if ts:
                tot["first"] = tot["first"] or ts
                tot["last"] = ts
            usage = (rec.get("message") or {}).get("usage") or {}
            tot["input"] += usage.get("input_tokens") or 0
            tot["output"] += usage.get("output_tokens") or 0
            tot["cache_read"] += usage.get("cache_read_input_tokens") or 0
            tot["cache_create"] += usage.get("cache_creation_input_tokens") or 0
    return tot


def find_transcript(session_id, projects_root):
    return next(iter(Path(projects_root).glob(f"*/{session_id}.jsonl")), None)


def find_subagent_transcripts(session_id, projects_root):
    """Transcripts of the agents a session dispatched. Claude Code writes them
    to <project>/<session-id>/subagents/agent-*.jsonl; before 0.6.0 the
    script never looked there, which hid about a fifth of all output tokens.
    """
    return sorted(Path(projects_root).glob(f"*/{session_id}/subagents/*.jsonl"))


def _parse_iso(ts):
    """ISO-8601 timestamp, tolerating a trailing 'Z' and fractional seconds."""
    if not ts:
        return None
    try:
        return datetime.fromisoformat(ts.replace("Z", "+00:00"))
    except ValueError:
        return None


def _earliest(a, b):
    if a is None:
        return b
    if b is None:
        return a
    pa, pb = _parse_iso(a), _parse_iso(b)
    if pa is not None and pb is not None:
        return a if pa <= pb else b
    return min(a, b)  # fall back to string compare only if parsing fails


def _latest(a, b):
    if a is None:
        return b
    if b is None:
        return a
    pa, pb = _parse_iso(a), _parse_iso(b)
    if pa is not None and pb is not None:
        return a if pa >= pb else b
    return max(a, b)  # fall back to string compare only if parsing fails


def compute(task_dir, projects_root):
    ledger_path = Path(task_dir) / "ledger.md"
    parsed = parse_ledger(ledger_path.read_text(encoding="utf-8"))
    totals = {k: 0 for k in KEYS}
    dispatched = {k: 0 for k in KEYS}
    dispatched["agents"] = 0
    sessions, missing, first, last = [], [], None, None
    for sid in dict.fromkeys(parsed["sessions"]):
        p = find_transcript(sid, projects_root)
        if p is None:
            missing.append(sid)
            continue
        u = sum_usage(p)
        subs = [sum_usage(sp) for sp in find_subagent_transcripts(sid, projects_root)]
        sub = {k: sum(s[k] for s in subs) for k in KEYS}
        for k in KEYS:
            totals[k] += u[k] + sub[k]
            dispatched[k] += sub[k]
        dispatched["agents"] += len(subs)
        rec = {"id": sid, "stage": parsed["session_stages"].get(sid), **u}
        rec["sub_agents"] = len(subs)
        for k in KEYS:
            rec["sub_" + k] = sub[k]
        sessions.append(rec)
        first = _earliest(first, u["first"])
        last = _latest(last, u["last"])

    by_stage = {}
    for s in sessions:
        b = by_stage.setdefault(s["stage"] or "unannotated",
                                {"input": 0, "output": 0, "cache_read": 0,
                                 "cache_create": 0, "count": 0})
        for k in KEYS:  # a dispatched agent inherits its parent session's stage
            b[k] += s[k] + s.get("sub_" + k, 0)
        b["count"] += 1

    return {"key": Path(task_dir).name, "sessions": sessions, "missing": missing,
            "totals": totals, "dispatched": dispatched, "by_stage": by_stage,
            "dispatch_models": parsed["dispatch_models"],
            "first": first, "last": last}


def _stage_sort_key(stage):
    if stage == "unannotated":
        return (2, 0, stage)  # always last
    if stage in STAGE_ORDER:
        return (0, STAGE_ORDER.index(stage), stage)
    return (1, 0, stage)  # unknown stage names between known and unannotated


def render_block(m):
    t = m["totals"]
    lines = [
        f"**Sessions:** {len(m['sessions'])}"
        + (f" ({len(m['missing'])} transcript(s) not found)" if m["missing"] else ""),
    ]
    for s in m["sessions"]:
        line = (f"- `{s['id'][:8]}` · {s.get('stage') or '—'} · "
                f"in {s['input']:,} · out {s['output']:,} · "
                f"cache-read {s['cache_read']:,}")
        if s.get("sub_agents"):
            line += f" · dispatched {s['sub_agents']} (out {s.get('sub_output', 0):,})"
        lines.append(line)
    lines += [
        f"**Tokens:** in {t['input']:,} · out {t['output']:,} · "
        f"cache-read {t['cache_read']:,} · cache-write {t['cache_create']:,}",
    ]
    d = m.get("dispatched") or {}
    if d.get("agents"):
        share = (100 * d["output"] // t["output"]) if t["output"] else 0
        lines.append(f"**Dispatched:** {d['agents']} agent(s) · in {d['input']:,} · "
                     f"out {d['output']:,} ({share}% of output) · "
                     f"cache-read {d['cache_read']:,}")
    lines.append(f"**Wall-clock:** {m['first'] or '?'} → {m['last'] or '?'}")
    by_stage = m.get("by_stage") or {}
    if any(stage != "unannotated" for stage in by_stage):
        parts = [f"{stage} in {b['input']:,} · out {b['output']:,} ({b['count']})"
                 for stage, b in sorted(by_stage.items(),
                                        key=lambda kv: _stage_sort_key(kv[0]))]
        lines.append("**By stage:** " + " — ".join(parts))
    models = m.get("dispatch_models") or {}
    if models:
        detail = " · ".join(f"{mdl} {n}" for mdl, n in sorted(models.items()))
        lines.append(f"**Dispatches:** {sum(models.values())} — {detail}")
    lines.append(f"*Computed {datetime.now().strftime(TS_FMT)} by task_metrics.py*")
    return "\n".join(lines)


def update_ledger_text(text, block):
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if pattern.search(text):
        return pattern.sub(BEGIN + "\n" + block + "\n" + END, text)

    marker_block = f"{BEGIN}\n{block}\n{END}\n"
    heading = METRICS_HEADING_RE.search(text)
    if heading:
        # A "## Metrics" heading exists but the marker pair doesn't -- insert
        # the markers at the end of that section (just before the next
        # top-level heading, or EOF) rather than adding a second heading.
        rest = text[heading.end():]
        next_heading = NEXT_HEADING_RE.search(rest)
        insert_at = heading.end() + (next_heading.start() if next_heading else len(rest))
        before, after = text[:insert_at], text[insert_at:]
        sep = "" if before.endswith("\n\n") else ("\n" if before.endswith("\n") else "\n\n")
        tail_sep = "\n" if after and not after.startswith("\n") else ""
        return before + sep + marker_block + tail_sep + after

    # No "## Metrics" heading at all: append a fresh section at EOF.
    sep = "" if text.endswith("\n") else "\n"
    return text + f"{sep}\n## Metrics\n\n{marker_block}"


def run_task(task_dir, projects_root, write):
    if not (Path(task_dir) / "ledger.md").exists():
        print(f"no ledger.md in {task_dir}")
        sys.exit(1)
    m = compute(task_dir, projects_root)
    block = render_block(m)
    print(f"== {m['key']} ==\n{block}\n")
    if write:
        ledger = Path(task_dir) / "ledger.md"
        original = ledger.read_text(encoding="utf-8")
        had_markers = BEGIN in original and END in original
        updated = update_ledger_text(original, block)
        if updated != original:
            ledger.write_text(updated, encoding="utf-8")
            if had_markers:
                print(f"(wrote metrics block to {ledger})")
            else:
                print(f"(no metrics markers found — appended a new Metrics "
                      f"section to {ledger})")
        else:
            print(f"(metrics block already up to date in {ledger})")
    return m


# --------------------------------------------------------------------------- stamp

def stamp_session(text, session_id, stage):
    """Add `- session: <id> · stage: <stage>` under the Metrics section's
    Sessions list. Idempotent: a session id already present is left alone
    (its first annotation wins, matching parse_ledger). Returns (text, changed).
    """
    if re.search(r"^\s*-\s*session:\s*" + re.escape(session_id) + r"\b", text, re.M):
        return text, False
    line = f"- session: {session_id} · stage: {stage}"
    heading = METRICS_HEADING_RE.search(text)
    if not heading:
        sep = "" if text.endswith("\n") else "\n"
        return text + f"{sep}\n## Metrics\n\n{SESSIONS_HEADER}\n\n{line}\n", True
    rest = text[heading.end():]
    next_heading = NEXT_HEADING_RE.search(rest)
    section_end = heading.end() + (next_heading.start() if next_heading else len(rest))
    section = text[heading.end():section_end]
    # insert after the last existing session line, else after the Sessions
    # header, else right after the heading (before any metrics markers)
    last_session = None
    for m in SESSION_RE.finditer(section):
        last_session = m
    if last_session:
        eol = section.find("\n", last_session.end())
        at = heading.end() + (eol + 1 if eol >= 0 else len(section))
        return text[:at] + line + "\n" + text[at:], True
    hdr = section.find(SESSIONS_HEADER)
    if hdr >= 0:
        eol = section.find("\n", hdr)
        at = heading.end() + eol + 1
        return text[:at] + "\n" + line + "\n" + text[at:], True
    at = heading.end()
    return text[:at] + f"\n\n{SESSIONS_HEADER}\n\n{line}\n" + text[at:], True


# --------------------------------------------------------------------------- index

_MD_LINK = re.compile(r"\[([^\]]+)\]\([^)]+\)")
_TS = re.compile(r"(\d{4}-\d{2}-\d{2})(?: (\d{2}:\d{2}))?")


def _plain(s):
    s = _MD_LINK.sub(r"\1", s)
    s = s.replace("**", "").replace("`", "").replace("*", "")
    return re.sub(r"\s+", " ", s).strip()


def _clip(s, n):
    if len(s) <= n:
        return s
    cut = s[:n].rsplit(" ", 1)[0]
    return (cut if len(cut) > n // 2 else s[:n]).rstrip(" ,;:-") + "…"


def _field(text, label):
    m = re.search(r"^- \*\*" + re.escape(label) + r":\*\*\s*(.*)$", text, re.M)
    return _plain(m.group(1)) if m else ""


def ledger_summary(ledger_path):
    """One INDEX row's worth of facts from a ledger, with hard caps so the
    index stays a scan surface rather than a second journal."""
    text = Path(ledger_path).read_text(encoding="utf-8", errors="replace")
    key = Path(ledger_path).parent.name
    title = key
    first_line = text.splitlines()[0] if text else ""
    m = re.match(r"^#\s+(\S+)\s+[—-]+\s+(.+?)\s*$", first_line)
    if m:
        title = _plain(m.group(2))
    stage_raw = _field(text, "Stage")
    stage = _clip(stage_raw, 70)
    done = bool(re.match(r"(?i)^\s*(done|closed|complete)", stage_raw))
    next_action = _clip(_field(text, "Next action"), 140)
    waiting = _clip(_field(text, "Waiting on"), 60)
    ts = _TS.search(_field(text, "Last done"))
    if ts:
        updated = ts.group(1) + (" " + ts.group(2) if ts.group(2) else "")
    else:
        updated = datetime.fromtimestamp(Path(ledger_path).stat().st_mtime).strftime("%Y-%m-%d")
    tok = re.search(r"\*\*Tokens:\*\*.*?out ([\d,]+)", text)
    sess = re.search(r"\*\*Sessions:\*\*\s*(\d+)", text)
    totals = f"out {tok.group(1)} · {sess.group(1)} sess" if tok and sess else "—"
    return {"key": key, "title": _clip(title, 80), "stage": stage or "—",
            "next": next_action or "—", "waiting": waiting or "—",
            "updated": updated, "done": done, "totals": totals}


def render_index(rows):
    active = sorted([r for r in rows if not r["done"]], key=lambda r: r["updated"], reverse=True)
    done = sorted([r for r in rows if r["done"]], key=lambda r: r["updated"], reverse=True)
    out = ["# Task Index", "", INDEX_BANNER, "",
           f"{len(active)} active · {len(done)} done · one row per ledger under this directory.", "",
           "| Key | Title | Stage | Next action | Waiting on | Updated | Totals |",
           "|---|---|---|---|---|---|---|"]
    for r in active + done:
        cells = [r[k].replace("|", "\\|") for k in
                 ("key", "title", "stage", "next", "waiting", "updated", "totals")]
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out) + "\n"


def regenerate_index(tasks_dir):
    rows = [ledger_summary(p) for p in sorted(Path(tasks_dir).glob("*/ledger.md"))]
    return render_index(rows), rows


# --------------------------------------------------------------------------- main

def main(argv=None):
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    argv = list(sys.argv[1:] if argv is None else argv)

    if argv and argv[0] == "index":
        ap = argparse.ArgumentParser(prog="task_metrics.py index")
        ap.add_argument("tasks_dir")
        ap.add_argument("--write", action="store_true", help="write INDEX.md (else print)")
        a = ap.parse_args(argv[1:])
        text, rows = regenerate_index(a.tasks_dir)
        if a.write:
            Path(a.tasks_dir, "INDEX.md").write_text(text, encoding="utf-8")
            print(f"INDEX.md regenerated: {len(rows)} rows "
                  f"({sum(1 for r in rows if r['done'])} done)")
        else:
            print(text)
        return 0

    if argv and argv[0] == "stamp":
        ap = argparse.ArgumentParser(prog="task_metrics.py stamp")
        ap.add_argument("task_dir")
        ap.add_argument("--session", required=True)
        ap.add_argument("--stage", required=True)
        a = ap.parse_args(argv[1:])
        ledger = Path(a.task_dir) / "ledger.md"
        text = ledger.read_text(encoding="utf-8")
        new, changed = stamp_session(text, a.session, a.stage)
        if changed:
            ledger.write_text(new, encoding="utf-8")
            print(f"stamped session {a.session[:8]} · stage: {a.stage}")
        else:
            print(f"session {a.session[:8]} already recorded")
        return 0

    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("path", help="task dir, or tasks root with --all")
    ap.add_argument("--all", action="store_true", help="aggregate every */ledger.md")
    ap.add_argument("--write", action="store_true", help="update ledger metrics block")
    ap.add_argument("--projects-root", default=str(DEFAULT_PROJECTS_ROOT))
    args = ap.parse_args(argv)
    root = Path(args.projects_root)
    if not args.all:
        run_task(args.path, root, args.write)
        return 0

    grand = {k: 0 for k in KEYS}
    tasks = missing_total = 0
    occurrences = {}
    first_seen = {}
    for ledger in sorted(Path(args.path).glob("*/ledger.md")):
        m = run_task(ledger.parent, root, args.write)
        tasks += 1
        missing_total += len(m["missing"])
        for s in m["sessions"]:
            occurrences[s["id"]] = occurrences.get(s["id"], 0) + 1
            first_seen.setdefault(s["id"], s)  # counted once: first task wins

    for s in first_seen.values():
        for k in grand:
            grand[k] += s[k] + s.get("sub_" + k, 0)
    shared_sessions = sum(1 for n in occurrences.values() if n > 1)

    print(f"== ALL: {tasks} task(s) · in {grand['input']:,} · out {grand['output']:,}"
          f" · cache-read {grand['cache_read']:,} · cache-write {grand['cache_create']:,} ==")
    if shared_sessions:
        print(f"(shared sessions counted once: {shared_sessions})")
    if missing_total:
        print(f"(transcripts missing: {missing_total})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
